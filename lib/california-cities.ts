// Function to search for cities by name with improved performance and fuzzy matching
export function searchCities(query: string): CityZipData[] {
  if (!query || query.length < 2) return []

  const normalizedQuery = query.toLowerCase().trim()

  // First try exact matches at the beginning of city or county name
  const exactMatches = californiaCities.filter(
    (city) =>
      city.city.toLowerCase().startsWith(normalizedQuery) || city.county.toLowerCase().startsWith(normalizedQuery),
  )

  // If we have exact matches, return those (limited to 10 for performance)
  if (exactMatches.length > 0) {
    return exactMatches.slice(0, 10)
  }

  // Otherwise, try partial matches
  const partialMatches = californiaCities.filter(
    (city) => city.city.toLowerCase().includes(normalizedQuery) || city.county.toLowerCase().includes(normalizedQuery),
  )

  // Return partial matches (limited to 10 for performance)
  return partialMatches.slice(0, 10)
}

// Function to get a city by exact name
export function getCityByName(name: string): CityZipData | undefined {
  const normalizedName = name.toLowerCase().trim()
  return californiaCities.find((city) => city.city.toLowerCase() === normalizedName)
}

// Function to check if a zip code is in California
export function isCaliforniaZipCode(zipCode: string): boolean {
  return californiaCities.some((city) => city.zipCodes.includes(zipCode))
}

// Function to get popular/common zip codes for a city (first 5 or fewer)
export function getPopularZipCodes(city: CityZipData): string[] {
  return city.zipCodes.slice(0, Math.min(5, city.zipCodes.length))
}

// California zip code ranges for fallback validation
export const CA_ZIP_RANGES = [
  [90001, 96162], // Main CA zip code range
]

// Function to validate if a zip code is in California using ranges
export function isCaliforniaZipByRange(zip: string): boolean {
  if (!/^\d{5}$/.test(zip)) return false

  const numZip = Number.parseInt(zip, 10)
  return CA_ZIP_RANGES.some(([min, max]) => numZip >= min && numZip <= max)
}

// Combined function to check if a zip code is valid for California
export function validateCaliforniaZip(zip: string): boolean {
  return isCaliforniaZipCode(zip) || isCaliforniaZipByRange(zip)
}
